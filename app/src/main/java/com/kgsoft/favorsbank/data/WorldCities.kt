/** Search cities by Arabic/English city or country name (case-insensitive). */
fun searchCities(query: String, limit: Int = 50): List<WorldCity> {
    val q = query.trim().lowercase()
    if (q.isEmpty()) return WORLD_CITIES.take(limit)
    return WORLD_CITIES.filter {
        it.cityAr.contains(query.trim()) ||
            it.countryAr.contains(query.trim()) ||
            it.cityEn.lowercase().contains(q) ||
            it.countryEn.lowercase().contains(q)
    }.take(limit)
}
